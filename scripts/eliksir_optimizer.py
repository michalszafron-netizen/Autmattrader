def rma(vals, length):
    r = np.full_like(vals, np.nan)
    a = 1.0 / length
    for i in range(len(vals)):
        if i < length: continue
        if np.isnan(r[i-1]): r[i] = np.mean(vals[max(0,i-length+1):i+1])
        else: r[i] = a * vals[i] + (1-a) * r[i-1]
    return r

def sma(vals, length):
    r = np.full_like(vals, np.nan)
    for i in range(length-1, len(vals)): r[i] = np.mean(vals[i-length+1:i+1])
    return r

def atr(h, l, c, length):
    tr = np.zeros_like(h)
    for i in range(1, len(h)): tr[i] = max(h[i]-l[i], abs(h[i]-c[i-1]), abs(l[i]-c[i-1]))
    return rma(tr, length)

def rsi_calc(vals, length):
    d = np.diff(vals)
    g = np.where(d > 0, d, 0)
    lo = np.where(d < 0, -d, 0)
    ag = np.full_like(vals, np.nan); al = np.full_like(vals, np.nan)
    if length >= len(vals): return ag
    ag[length] = np.mean(g[:length]); al[length] = np.mean(lo[:length])
    for i in range(length+1, len(vals)):
        ag[i] = (ag[i-1]*(length-1)+g[i-1])/length
        al[i] = (al[i-1]*(length-1)+lo[i-1])/length
    rs = np.where(al == 0, 100, ag/al)
    r = 100 - (100/(1+rs)); r[:length] = np.nan
    return r

def run(params):
    th, sl, tp, rl, mf, ms = params['th'], params['sl'], params['tp'], params['rl'], params['mf'], params['ms']
    macd_f, macd_s, macd_sig = params['macd_f'], params['macd_s'], params['macd_sig']
    ml, al = params['ml'], params['al']
    
    atr_v = atr(highs, lows, closes, al)
    rsi_v = rsi_calc(closes, rl)
    ma_f = sma(closes, mf)
    ma_s = sma(closes, ms)
    
    ema_f = rma(closes, macd_f); ema_s = rma(closes, macd_s)
    macd_line = ema_f - ema_s; macd_signal = rma(macd_line, macd_sig)
    macd_hist = macd_line - macd_signal
    
    mom = np.full(n, np.nan)
    for i in range(ml, n): mom[i] = (closes[i]-closes[i-ml])/closes[i-ml]*100
    
    pos = 0; entry = 0; trades = []
    warmup = int(max(80, rl*3, mf*2, ms, macd_s*2, ml*3, al*2))
    
    for i in range(warmup, n):
        if np.isnan(rsi_v[i]) or np.isnan(ma_f[i]) or np.isnan(atr_v[i]): continue
        
        bull, bear = 0, 0
        if rsi_v[i] < 30: bull += 2
        elif rsi_v[i] > 70: bear += 2
        elif rsi_v[i] < 40: bull += 1
        elif rsi_v[i] > 60: bear += 1
        
        if not np.isnan(ma_f[i]) and not np.isnan(ma_s[i]):
            if ma_f[i] > ma_s[i] and closes[i] > ma_f[i]: bull += 2
            elif ma_f[i] < ma_s[i] and closes[i] < ma_f[i]: bear += 2
        
        if not np.isnan(macd_line[i]) and not np.isnan(macd_hist[i]):
            if macd_line[i] > macd_signal[i] and macd_hist[i] > 0: bull += 1
            elif macd_line[i] < macd_signal[i] and macd_hist[i] < 0: bear += 1
            if macd_hist[i] > macd_hist[i-1] and macd_hist[i] > 0: bull += 1
            elif macd_hist[i] < macd_hist[i-1] and macd_hist[i] < 0: bear += 1
        
        if not np.isnan(mom[i]):
            if mom[i] > 0.5: bull += 1
            elif mom[i] < -0.5: bear += 1
        
        net = bull - bear
        
        if pos == 0:
            if net >= th: pos, entry = 1, closes[i]
            elif net <= -th: pos, entry = -1, closes[i]
        elif pos == 1:
            sl_p = entry - atr_v[i]*sl; tp_p = entry + atr_v[i]*tp
            hs = closes[i] <= sl_p; ht = closes[i] >= tp_p
            ep = sl_p if hs else (tp_p if ht else closes[i])
            if hs or ht or (not np.isnan(rsi_v[i]) and rsi_v[i] > 78) or net <= -1:
                trades.append((ep-entry)/entry*100); pos = 0
        elif pos == -1:
            sl_p = entry + atr_v[i]*sl; tp_p = entry - atr_v[i]*tp
            hs = closes[i] >= sl_p; ht = closes[i] <= tp_p
            ep = sl_p if hs else (tp_p if ht else closes[i])
            if hs or ht or (not np.isnan(rsi_v[i]) and rsi_v[i] < 22) or net >= 1:
                trades.append((entry-ep)/entry*100); pos = 0
    
    nt = len(trades)
    if nt < 30: return None
    
    wins = [t for t in trades if t > 0]
    losses = [t for t in trades if t <= 0]
    tp_ = sum(wins) if wins else 0; tl = abs(sum(losses)) if losses else 1
    pf = tp_/tl; wr = len(wins)/nt*100
    return {'pf': pf, 'n': nt, 'wr': wr, 'total': sum(trades),
            'aw': np.mean(wins) if wins else 0, 'al': np.mean(losses) if losses else 0}

